// Opt-in screenshots use only the existing isolated E2E server and synthetic data.
const { test, expect } = require('@playwright/test')
const path = require('path')
const output = path.resolve(__dirname, '../../../docs/screenshots')

test.skip(!process.env.GAMECS_CAPTURE_DEMO, 'Set GAMECS_CAPTURE_DEMO=1 to capture synthetic screenshots')
test.use({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })

test('capture player, support and assistant views', async ({ browser }) => {
  const player = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await player.goto('http://127.0.0.1:5175/')
  await player.getByRole('textbox', {name:'用户名'}).fill('e2e_player')
  await player.getByRole('textbox', {name:'密码'}).fill('test-password')
  await player.getByRole('button', {name:'登录', exact:false}).click()
  await player.getByRole('button', {name:'提交问题', exact:true}).click()
  await player.getByRole('combobox', {name:'游戏', exact:true}).selectOption({label:'测试游戏'})
  await player.getByRole('combobox', {name:'版本'}).selectOption({label:'测试版本'})
  await player.getByRole('combobox', {name:'问题分类'}).selectOption({label:'测试分类'})
  await player.getByRole('textbox', {name:'问题标题'}).fill('登录失败，需要协助')
  await player.getByRole('textbox', {name:'详细描述'}).fill('更新客户端后无法登录，切换网络后仍提示连接失败。')
  await player.screenshot({path: path.join(output, 'player-ticket.png'), fullPage: true})
  await player.getByRole('button', {name:'提交工单'}).click()
  await expect(player.getByRole('heading', {name:'登录失败，需要协助'})).toBeVisible()

  const staff = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await staff.goto('http://127.0.0.1:5176/')
  await staff.getByRole('textbox', {name:'用户名'}).fill('e2e_staff')
  await staff.getByRole('textbox', {name:'密码'}).fill('test-password')
  await staff.getByRole('button', {name:'登录工作台'}).click()
  await staff.getByRole('button', {name:'02 待接工单'}).click()
  const row = staff.locator('article.ticket-row').filter({hasText:'登录失败，需要协助'})
  await row.getByRole('button', {name:'查看详情'}).click()
  await expect(staff.locator('.detail-content').filter({hasText:'更新客户端后无法登录'})).toBeVisible()
  await staff.getByRole('button', {name:'接单'}).click()
  await staff.getByRole('button', {name:'03 我的处理'}).click()
  await staff.getByRole('textbox', {name:'回复内容'}).fill('您好，请先确认客户端版本，并尝试清理缓存后重新登录。')
  await staff.getByRole('button', {name:'发送回复'}).click()
  await expect(staff.getByText('您好，请先确认客户端版本，并尝试清理缓存后重新登录。')).toBeVisible()
  await expect(staff.getByText(/正在加载/)).toHaveCount(0)
  await expect(staff.locator('.el-message')).toHaveCount(0)
  await staff.screenshot({path: path.join(output, 'staff-ticket.png'), fullPage: true})

  await player.getByRole('button', {name:'客服助手'}).click()
  await player.getByRole('combobox', {name:'选择游戏'}).selectOption({label:'测试游戏'})
  await player.getByRole('textbox', {name:'你的问题'}).fill('登录失败怎么办？')
  await player.getByRole('button', {name:'发送问题'}).click()
  await expect(player.getByText('请先检查网络。')).toBeVisible()
  await expect(player.getByText('参考：测试知识')).toBeVisible()
  await expect(player.getByText('工单已提交，可在详情中添加图片')).toBeHidden()
  await player.screenshot({path: path.join(output, 'assistant-answer.png'), fullPage: true})
  await player.close()
  await staff.close()
})
