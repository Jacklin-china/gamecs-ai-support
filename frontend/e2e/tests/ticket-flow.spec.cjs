const { test, expect } = require('@playwright/test')

test('player and staff complete a ticket conversation and rating', async ({ browser }) => {
  const player = await browser.newPage()
  const staff = await browser.newPage()
  await player.goto('http://127.0.0.1:5175/')
  await player.getByRole('textbox', {name:'用户名'}).fill('e2e_player')
  await player.getByRole('textbox', {name:'密码'}).fill('test-password')
  await player.getByRole('button', {name:'登录', exact:false}).click()
  await player.getByRole('button', {name:'提交问题', exact:true}).click()
  await player.getByRole('combobox', {name:'游戏', exact:true}).selectOption({label:'测试游戏'})
  await player.getByRole('combobox', {name:'版本'}).selectOption({label:'测试版本'})
  await player.getByRole('combobox', {name:'问题分类'}).selectOption({label:'测试分类'})
  await player.getByRole('textbox', {name:'问题标题'}).fill('隔离验收工单')
  await player.getByRole('textbox', {name:'详细描述'}).fill('登录后出现问题')
  await player.getByRole('button', {name:'提交工单'}).click()
  await expect(player.getByRole('heading', {name:'隔离验收工单'})).toBeVisible()
  await player.getByRole('textbox', {name:'回复内容'}).fill('补充问题信息')
  await player.getByRole('button', {name:'发送回复'}).click()
  await expect(player.getByText('补充问题信息')).toBeVisible()

  await staff.goto('http://127.0.0.1:5176/')
  await staff.getByRole('textbox', {name:'用户名'}).fill('e2e_staff')
  await staff.getByRole('textbox', {name:'密码'}).fill('test-password')
  await staff.getByRole('button', {name:'登录工作台'}).click()
  await staff.getByRole('button', {name:'02 待接工单'}).click()
  await expect(staff.getByText('补充问题信息')).toBeVisible()
  await staff.getByRole('button', {name:'接单'}).click()
  await staff.getByRole('button', {name:'03 我的处理'}).click()
  await staff.getByRole('textbox', {name:'回复内容'}).fill('客服已处理')
  await staff.getByRole('button', {name:'发送回复'}).click()
  await expect(staff.getByText('客服已处理')).toBeVisible()
  await staff.getByRole('textbox', {name:'处理结果'}).fill('问题已解决')
  await staff.getByRole('button', {name:'完成工单'}).click()

  await player.getByRole('button', {name:'热点舆情'}).click()
  await player.getByRole('button', {name:'我的工单', exact:true}).click()
  await player.getByRole('button', {name:/隔离验收工单.*已完成/}).click()
  await expect(player.getByText('客服已处理')).toBeVisible()
  await expect(player.getByText('问题已解决')).toBeVisible()
  await player.getByRole('textbox', {name:'评价内容（可选）'}).fill('感谢处理')
  await player.getByRole('button', {name:'提交评价并确认解决'}).click()
  await expect(player.getByText('评价：5 / 5 感谢处理')).toBeVisible()
  await player.close()
  await staff.close()
})
